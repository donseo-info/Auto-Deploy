// --- Диагностика окружения ---

function check_env() {
    $results = [];

    // Путь и пользователь
    $results['dir']  = ok(__DIR__);
    $results['user'] = ok(trim(shell('whoami')));

    // shell_exec
    $test = shell('echo ok');
    $results['shell_exec'] = trim($test) === 'ok'
        ? ok('Доступен')
        : err('Заблокирован — деплой невозможен');

    // git
    $git = shell('git --version');
    $results['git'] = str_contains($git, 'git version')
        ? ok(trim($git))
        : err('Git не найден');

    // Права на запись
    $results['writable'] = is_writable(__DIR__)
        ? ok('Папка доступна для записи')
        : err('Нет прав на запись в папку');

    return $results;
}

// --- Проверка репозитория ---

function check_repo($dir, $branch) {
    $results = [];

    // Существует ли папка
    if (!is_dir($dir)) {
        $results['dir'] = err("Папка не существует: {$dir}");
        return $results;
    }
    $results['dir'] = ok("Папка существует");

    // Есть ли .git
    $status = shell("cd " . escapeshellarg($dir) . " && git status");
    if (str_contains($status, 'not a git repository')) {
        $results['git_repo'] = err('Репозиторий не инициализирован — нужен git clone/init');
        return $results;
    }
    $results['git_repo'] = ok('Git репозиторий найден');

    // Текущая ветка
    $current_branch = trim(shell("cd " . escapeshellarg($dir) . " && git branch --show-current"));
    if ($current_branch !== $branch) {
        $results['branch'] = warn("Текущая ветка: '{$current_branch}', ожидается: '{$branch}'");
    } else {
        $results['branch'] = ok("Ветка: {$branch}");
    }

    // Remote
    $remote = trim(shell("cd " . escapeshellarg($dir) . " && git remote get-url origin"));
    if (empty($remote)) {
        $results['remote'] = err('Remote origin не настроен');
    } else {
        $results['remote'] = ok("Remote: {$remote}");
    }

    // Тест git fetch
    $fetch = shell("cd " . escapeshellarg($dir) . " && git fetch origin");
    if (str_contains($fetch, 'Permission denied') || str_contains($fetch, 'fatal')) {
        $results['fetch'] = err("Ошибка fetch: {$fetch}");
    } else {
        $results['fetch'] = ok('git fetch origin — успешно');
    }

    return $results;
}

// --- Инициализация репо ---

function init_repo($dir, $repo_url, $branch) {
    $log = [];

    // git init
    $out = shell("cd " . escapeshellarg($dir) . " && git init");
    $log[] = ['cmd' => 'git init', 'out' => $out];

    // remote add
    $out = shell("cd " . escapeshellarg($dir) . " && git remote add origin " . escapeshellarg($repo_url));
    $log[] = ['cmd' => 'git remote add origin', 'out' => $out];

    // fetch
    $out = shell("cd " . escapeshellarg($dir) . " && git fetch origin");
    $log[] = ['cmd' => 'git fetch origin', 'out' => $out];

    // checkout branch
    $out = shell("cd " . escapeshellarg($dir) . " && git checkout -b {$branch} origin/{$branch}");
    if (str_contains($out, 'already exists')) {
        $out = shell("cd " . escapeshellarg($dir) . " && git checkout {$branch}");
    }
    $log[] = ['cmd' => "git checkout {$branch}", 'out' => $out];

    // reset hard
    $out = shell("cd " . escapeshellarg($dir) . " && git reset --hard origin/{$branch}");
    $log[] = ['cmd' => "git reset --hard origin/{$branch}", 'out' => $out];

    return $log;
}

