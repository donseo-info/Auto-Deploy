function generate_deploy($dir, $branch, $secret) {
    return <<<PHP
<?php
/**
 * Auto-Deploy Webhook
 * Generated by Git Installer v1.0
 */

define('SECRET',      '{$secret}');
define('PROJECT_DIR', '{$dir}');
define('LOG_FILE',    __DIR__ . '/deploy.log');
define('BRANCH',      '{$branch}');

\$payload   = file_get_contents('php://input');
\$signature = \$_SERVER['HTTP_X_HUB_SIGNATURE_256'] ?? '';
\$expected  = 'sha256=' . hash_hmac('sha256', \$payload, SECRET);

log_msg('Webhook получен');

if (!\$signature || !hash_equals(\$expected, \$signature)) {
    http_response_code(403);
    log_msg('ОШИБКА: неверная подпись');
    die('Forbidden');
}

\$data = json_decode(\$payload, true);
\$ref  = \$data['ref'] ?? '';

if (\$ref !== 'refs/heads/' . BRANCH) {
    log_msg("Пропуск: ветка {\$ref}");
    die('Not target branch');
}

log_msg('=== Деплой начат ===');

\$commands = [
    'git fetch origin',
    'git reset --hard origin/' . BRANCH,
];

foreach (\$commands as \$cmd) {
    \$out = shell_exec('cd ' . escapeshellarg(PROJECT_DIR) . " && {\$cmd} 2>&1");
    log_msg("[{\$cmd}]\\n" . trim(\$out));
}

log_msg('=== Готово ===');
http_response_code(200);
echo 'OK';

function log_msg(\$msg) {
    file_put_contents(LOG_FILE, date('Y-m-d H:i:s') . ' ' . \$msg . PHP_EOL, FILE_APPEND);
}
PHP;
}

