// --- Helpers ---

function shell($cmd) {
    return shell_exec($cmd . ' 2>&1');
}

function ok($msg) {
    return ['status' => 'ok', 'msg' => $msg];
}

function err($msg) {
    return ['status' => 'error', 'msg' => $msg];
}

function warn($msg) {
